// Turns the full-size loading illustration into the two things the loading
// screen actually ships: a small WebP with a feathered alpha edge, and an inline
// base64 thumbnail that paints before the WebP has finished downloading.
//
// The source art is a 2.4 MB opaque PNG. Shipping it as-is meant the loading
// screen's own background was a bigger download than the code it was covering
// for, and it arrived as a hard-edged rectangle over the overlay gradient. The
// alpha ramp baked in here lets it dissolve into that gradient instead, which is
// cheaper than a CSS mask (no extra compositing layer during shader compile).
import { promises as fs } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SOURCE_PATH = path.resolve('assets-source/GameLoad.png');
const OUTPUT_PATH = path.resolve('public/Assets/GameLoad.webp');
const MODULE_PATH = path.resolve('src/generated/loadingArt.js');

const OUTPUT_WIDTH = 1280;
// The art is only ever seen through a dark scrim at partial opacity, so quality
// past the high 60s buys detail nobody can see. 68 lands around 110 KB.
const WEBP_QUALITY = 68;
const LQIP_WIDTH = 24;

// Fractions of each dimension over which alpha ramps from 0 at the edge to 1.
// The bottom gets the longest ramp because the START button and the roster cards
// sit there, and a visible seam behind them reads as a rendering bug.
const FEATHER = { left: 0.13, right: 0.13, top: 0.10, bottom: 0.26 };
// Corner darkening, applied on top of the edge ramps.
const VIGNETTE_STRENGTH = 0.22;
const VIGNETTE_START = 0.40;

function smoothstep(edge0, edge1, value) {
  const t = Math.max(0, Math.min(1, (value - edge0) / (edge1 - edge0)));
  return t * t * (3 - 2 * t);
}

// One channel of 8-bit coverage, laid out row-major to match sharp's raw format.
function buildFeatherMask(width, height) {
  const mask = Buffer.allocUnsafe(width * height);
  for (let y = 0; y < height; y++) {
    const v = (y + 0.5) / height;
    const vertical = smoothstep(0, FEATHER.top, v) * smoothstep(0, FEATHER.bottom, 1 - v);
    for (let x = 0; x < width; x++) {
      const u = (x + 0.5) / width;
      const edges = vertical * smoothstep(0, FEATHER.left, u) * smoothstep(0, FEATHER.right, 1 - u);
      // Squashed vertically so a 16:9 frame does not darken top and bottom first.
      const distance = Math.hypot(u - 0.5, (v - 0.5) * 0.9);
      const vignette = 1 - VIGNETTE_STRENGTH * smoothstep(VIGNETTE_START, 0.78, distance);
      mask[y * width + x] = Math.round(255 * edges * vignette);
    }
  }
  return mask;
}

async function main() {
  const source = sharp(SOURCE_PATH);
  const metadata = await source.metadata();
  const height = Math.round((OUTPUT_WIDTH * metadata.height) / metadata.width);

  const rgb = await sharp(SOURCE_PATH)
    .resize({ width: OUTPUT_WIDTH, height, fit: 'fill' })
    .removeAlpha()
    .raw()
    .toBuffer();

  const mask = buildFeatherMask(OUTPUT_WIDTH, height);
  const feathered = () => sharp(rgb, { raw: { width: OUTPUT_WIDTH, height, channels: 3 } })
    .joinChannel(mask, { raw: { width: OUTPUT_WIDTH, height, channels: 1 } });

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await feathered()
    .webp({ quality: WEBP_QUALITY, alphaQuality: 72, effort: 6 })
    .toFile(OUTPUT_PATH);

  // Opaque on purpose: an alpha plane costs a WebP this small ~3 KB, more than
  // twenty times the pixel data. The placeholder gets its soft edge from a CSS
  // mask instead, which is free. Upscaling 24px to full bleed is its own blur.
  const lqipHeight = Math.max(1, Math.round((LQIP_WIDTH * height) / OUTPUT_WIDTH));
  const lqip = await sharp(rgb, { raw: { width: OUTPUT_WIDTH, height, channels: 3 } })
    .resize({ width: LQIP_WIDTH, height: lqipHeight, fit: 'fill' })
    .webp({ quality: 30, effort: 6 })
    .toBuffer();

  await fs.mkdir(path.dirname(MODULE_PATH), { recursive: true });
  await fs.writeFile(MODULE_PATH, `// Generated by scripts/optimize-loading-art.mjs.
export const LOADING_ART_SRC = 'Assets/${path.basename(OUTPUT_PATH)}';
export const LOADING_ART_WIDTH = ${OUTPUT_WIDTH};
export const LOADING_ART_HEIGHT = ${height};
export const LOADING_ART_LQIP = 'data:image/webp;base64,${lqip.toString('base64')}';
`, 'utf8');

  const { size } = await fs.stat(OUTPUT_PATH);
  const sourceSize = (await fs.stat(SOURCE_PATH)).size;
  console.info(`[loading-art] ${OUTPUT_WIDTH}x${height} webp ${(size / 1024).toFixed(0)} KB `
    + `(from ${(sourceSize / 1024 / 1024).toFixed(1)} MB), lqip ${lqip.length} B`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
