import { promises as fs } from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const CONFIG_PATH = path.resolve('public/config.yaml');
const PUBLIC_DIR = path.resolve('public');
const OUTPUT_PATH = path.resolve('src/generated/leafVariants.js');
const LEAF_FILE_PATTERN = /^leaf-(green|yellow|whites?)(?:[-_](\d+))?\.png$/i;
const ZONE_ALIASES = {
  green: 'green',
  yellow: 'yellow',
  white: 'white',
  whites: 'white',
};

function getLeafDirectory(config) {
  const configuredPaths = Object.values(config.assets?.leaves ?? {}).filter(Boolean);
  if (configuredPaths.length === 0) {
    throw new Error('config.assets.leaves must contain at least one leaf asset');
  }

  const directory = path.posix.dirname(configuredPaths[0]);
  for (const assetPath of configuredPaths.slice(1)) {
    if (path.posix.dirname(assetPath) !== directory) {
      throw new Error('All configured leaf assets must use the same directory');
    }
  }
  return directory;
}

function groupLeafFiles(fileNames) {
  const groups = new Map();
  for (const fileName of fileNames) {
    const match = LEAF_FILE_PATTERN.exec(fileName);
    if (!match) continue;

    const zone = ZONE_ALIASES[match[1].toLowerCase()];
    const variant = match[2] ? Number(match[2]) : null;
    const entries = groups.get(zone) ?? [];
    entries.push({ fileName, variant });
    groups.set(zone, entries);
  }
  return groups;
}

function selectLeafVariants(entries) {
  const legacy = entries
    .filter((entry) => entry.variant === null)
    .sort((left, right) => left.fileName.localeCompare(right.fileName));
  const numbered = entries.filter((entry) => Number.isInteger(entry.variant));
  const hasExplicitFirstVariant = numbered.some((entry) => entry.variant === 1);
  const selected = [...numbered];

  if (!hasExplicitFirstVariant && legacy.length > 0) {
    selected.push({ ...legacy[0], variant: 1 });
  }

  if (selected.length === 0) return legacy;
  return selected.sort(
    (left, right) => left.variant - right.variant || left.fileName.localeCompare(right.fileName),
  );
}

function buildModule(manifest) {
  return `// Generated by scripts/generate-leaf-variants.mjs.\nexport const LEAF_VARIANTS = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
}

async function main() {
  const config = yaml.load(await fs.readFile(CONFIG_PATH, 'utf8'));
  const assetDirectory = getLeafDirectory(config);
  const fileDirectory = path.join(PUBLIC_DIR, assetDirectory);
  const groups = groupLeafFiles(await fs.readdir(fileDirectory));
  const manifest = {};

  for (const zone of Object.keys(config.assets.leaves)) {
    const entries = selectLeafVariants(groups.get(zone) ?? []);
    manifest[zone] = entries.length > 0
      ? entries.map(({ fileName }) => path.posix.join(assetDirectory, fileName))
      : [config.assets.leaves[zone]].filter(Boolean);
  }

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, buildModule(manifest), 'utf8');
  console.log(`Leaf variants: ${path.relative(process.cwd(), OUTPUT_PATH)}`);
  for (const [zone, variants] of Object.entries(manifest)) {
    console.log(`  ${zone}: ${variants.length} variant${variants.length === 1 ? '' : 's'}`);
  }
}

main().catch((error) => {
  console.error('Failed to generate leaf variants:', error);
  process.exitCode = 1;
});
